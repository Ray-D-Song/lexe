const CRYPTO_STR_CONSTANTS: &[(&str, &str)] = &[("defaultCoreCipherList", DEFAULT_CIPHER_LIST)];

/// Visit every crypto/OpenSSL constant exposed by Node's `constants` module.
pub fn visit_crypto_constants(
    mut on_i32: impl FnMut(&'static str, i32) -> Result<()>,
    mut on_u32: impl FnMut(&'static str, f64) -> Result<()>,
    mut on_str: impl FnMut(&'static str, &'static str) -> Result<()>,
) -> Result<()> {
    for &(name, val) in CRYPTO_I32_CONSTANTS {
        on_i32(name, val)?;
    }
    for &(name, val) in CRYPTO_U32_CONSTANTS {
        on_u32(name, f64::from(val))?;
    }
    for &(name, val) in CRYPTO_STR_CONSTANTS {
        on_str(name, val)?;
    }
    Ok(())
}
